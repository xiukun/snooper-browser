import assert from 'node:assert/strict'
import { harness, modules, noteEntry, recording } from './library-test-harness.mjs'
const h=harness(modules)
try {
let a=await h.load()
const id=await recording(a,1,451)
const first={kind:'transcript',recordId:id,lineId:'line-0'}, last={...first,lineId:'line-450'}
await a.library.setFavorite(first,true); await a.library.setFavorite(last,true)
assert.equal((await a.library.listFavorites()).length,2)
await a.library.setFavorite(first,false)
assert.equal((await a.transcripts.readTranscript(id)).length,451)
await a.library.setFavorite(first,true)
await a.notes.addNoteEntry({noteId:'n',entry:noteEntry('e','独立电脑',{imageUrl:'data:image/png;base64,SECRET_IMAGE'})})
const nr={kind:'note',noteId:'n',entryId:'e'}
await a.library.setFavorite(nr,true)
const context=await a.library.libraryContext(last)
assert.equal(context.entry.source,'computer 450')
assert.equal(context.before.length+context.after.length>0,true)
assert.equal(JSON.stringify(await a.library.libraryContext(nr)).includes('SECRET_IMAGE'),false)
let p=await a.library.prepareDelete({transcriptIds:[id]})
assert.equal(p.favoriteCount,2)
await a.library.setFavorite(first,false)
await assert.rejects(a.library.confirmDelete(p.token),/重新确认/)
p=await a.library.prepareDelete({noteIds:['n']})
await a.notes.addNoteEntry({noteId:'n',entry:noteEntry('new')})
await assert.rejects(a.library.confirmDelete(p.token),/重新确认/)
p=await a.library.prepareDelete({noteIds:['n']})
const held=h.hold('set',a.library.DELETIONS_KEY)
const deleting=a.library.confirmDelete(p.token)
await held.entered
const adding=a.notes.addNoteEntry({noteId:'n',entry:noteEntry('during')})
held.release(); await deleting; await adding
assert.deepEqual((await a.notes.listNotes())[0].entries.map(e=>e.id),['during'],'queued add after confirm survives')
p=await a.library.prepareDelete({transcriptIds:[id]})
h.fail('set',a.transcripts.TRANSCRIPT_INDEX_KEY)
const partial=await a.library.confirmDelete(p.token)
assert.equal(partial.pending.length,1)
assert.equal(partial.completed.length,0)
a=await h.load()
await assert.rejects(a.library.libraryContext(last),/不存在|删除|缺块/)
const done=await a.library.retryDelete(partial.operationId)
assert.equal(done.pending.length,0)
assert.equal((await a.library.listFavorites()).filter(f=>f.ref.kind==='transcript').length,0)
assert.equal((await a.notes.listNotes())[0].entries[0].id,'during')
assert.deepEqual((await a.library.retryDelete(partial.operationId)).completed,done.completed)
assert.deepEqual((await a.library.confirmDelete(partial.operationId)).completed,done.completed,'a retried confirmed token uses its durable exact authorization')
await a.notes.addNoteEntry({noteId:'partial',entry:noteEntry('old')})
p=await a.library.prepareDelete({noteIds:['partial']})
h.fail('set',a.notes.NOTES_STORAGE_KEY)
const noteFailure=await a.library.confirmDelete(p.token)
await a.notes.addNoteEntry({noteId:'partial',entry:noteEntry('later')})
a=await h.load(); await a.library.recoverLibraryDeletions()
assert.deepEqual((await a.notes.listNotes()).find(n=>n.id==='partial').entries.map(e=>e.id),['later'],'restart only deletes confirmed IDs')
assert.equal((await a.library.retryDelete(noteFailure.operationId)).pending.length,0)
// Persistent source-deletion faults must not hide the durable retry operation.
const stuck=await recording(a,46,1)
p=await a.library.prepareDelete({transcriptIds:[stuck]})
h.failPersistent('remove',`${a.transcripts.TRANSCRIPT_CHUNK_PREFIX}${stuck}.0`)
const stuckDelete=await a.library.confirmDelete(p.token)
assert.equal(stuckDelete.pending.length,1)
let partialUsage=await a.library.libraryUsage()
assert.equal(partialUsage.complete,false)
assert.equal(partialUsage.transcriptCount,null)
assert.equal(partialUsage.pendingDeletes[0].operationId,stuckDelete.operationId)
assert.ok(partialUsage.errors.some(e=>e.area==='transcripts'))
a=await h.load();await a.library.recoverLibraryDeletions()
partialUsage=await a.library.libraryUsage()
assert.equal(partialUsage.pendingDeletes[0].operationId,stuckDelete.operationId)
h.clearFault();await a.library.retryDelete(stuckDelete.operationId)
h.fail('bytes')
const missingBytes=await a.library.libraryUsage()
assert.equal(missingBytes.bytes,null);assert.equal(missingBytes.complete,false)
assert.ok(missingBytes.errors.some(e=>e.area==='bytes' && /injected/.test(e.message)))
// Favorite writes must acknowledge persistence; reference-cleanup failures stay pending.
await a.notes.addNoteEntry({noteId:'cleanup',entry:noteEntry('ref')})
const cleanupRef={kind:'note',noteId:'cleanup',entryId:'ref'}
h.fail('set',a.library.FAVORITES_KEY)
await assert.rejects(a.library.setFavorite(cleanupRef,true),/injected/)
assert.equal((await a.library.listFavorites()).some(f=>f.ref.noteId==='cleanup'),false)
await a.library.setFavorite(cleanupRef,true)
p=await a.library.prepareDelete({noteIds:['cleanup']})
h.fail('set',a.library.FAVORITES_KEY)
const cleanupFailure=await a.library.confirmDelete(p.token)
assert.equal(cleanupFailure.pending.length,1)
assert.equal((await a.notes.listNotes()).some(n=>n.id==='cleanup'),false)
assert.equal((await a.library.listFavorites()).some(f=>f.ref.noteId==='cleanup'),true)
await assert.rejects(a.library.libraryContext(cleanupRef),/删除|不存在/)
a=await h.load();await a.library.recoverLibraryDeletions()
assert.equal((await a.library.listFavorites()).some(f=>f.ref.noteId==='cleanup'),false)
assert.equal((await a.library.retryDelete(cleanupFailure.operationId)).pending.length,0)
// Missing bodies must never become available merely because a reference remains.
const broken=await recording(a,45,1)
const brokenRef={kind:'transcript',recordId:broken,lineId:'line-0'}
await a.library.setFavorite(brokenRef,true)
delete h.local[`${a.transcripts.TRANSCRIPT_CHUNK_PREFIX}${broken}.0`]
await assert.rejects(a.library.libraryContext(brokenRef),/缺块/)
await assert.rejects(a.library.setFavorite(brokenRef,true),/缺块/)
const dangling=await a.library.prepareDelete({transcriptIds:[broken]})
assert.equal(dangling.favoriteCount,1)
await a.library.confirmDelete(dangling.token)
// A same-sized replacement of affected favorites still invalidates confirmation.
await a.notes.addNoteEntry({noteId:'swap',entry:noteEntry('a')})
await a.notes.addNoteEntry({noteId:'swap',entry:noteEntry('b')})
const fa={kind:'note',noteId:'swap',entryId:'a'},fb={...fa,entryId:'b'}
await a.library.setFavorite(fa,true)
p=await a.library.prepareDelete({noteIds:['swap']})
await a.library.setFavorite(fa,false);await a.library.setFavorite(fb,true)
await assert.rejects(a.library.confirmDelete(p.token),/重新确认/)
p=await a.library.prepareDelete({noteIds:['swap']})
h.fail('set',a.library.DELETIONS_KEY)
await assert.rejects(a.library.confirmDelete(p.token),/injected/)
assert.equal((await a.notes.listNotes()).find(n=>n.id==='swap').entries.length,2,'journal failure leaves original body intact')
await a.library.confirmDelete(p.token)
const usage=await a.library.libraryUsage()
assert.equal(usage.bytes,Buffer.byteLength(JSON.stringify(h.local)))
assert.equal(usage.noteCount,2)
console.log('✅ library-store: stable favorites, body context, confirmation changes, concurrent add, partial failure/restart/exact scope and real bytes passed')
} finally {h.close()}
